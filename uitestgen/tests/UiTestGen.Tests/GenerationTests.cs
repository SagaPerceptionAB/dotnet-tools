    [Test]
    public void Values_are_deterministic_and_independent_per_field()
    {
        string Values(FormPlan p) => string.Join("|", p.Fields.Select(f => f.Valid is null ? "-" : f.Valid.Text + f.Valid.Checked)) + "#" +
            string.Join("|", p.Cases.Select(c => $"{c.Field.Name}.{c.Rule.Kind}={c.Value.Text}{c.Value.Checked}"));
        var first = Values(Plan());
        Assert.That(Values(Plan()), Is.EqualTo(first));
        Assert.That(Values(Plan(seed: 1)), Is.Not.EqualTo(Values(Plan(seed: 2))));

        // Tas ett annat fält bort ändras inte värdet för de som är kvar.
        var form = SignupForm();
        var fewer = form with { Fields = form.Fields.Where(f => f.Name is not ("Site" or "Born")).ToList() };
        var all = Plan().Fields.ToDictionary(f => f.Field.Name, f => f.Valid);
        foreach (var f in Plan(fewer).Fields) Assert.That(f.Valid, Is.EqualTo(all[f.Field.Name]), f.Field.Name);

        // Och hela filerna är lika.
        var tests = SignupTests();
        Assert.That(SignupTests(), Is.EqualTo(tests));
        Assert.That(SignupTests(Options() with { Seed = 7 }), Is.Not.EqualTo(tests));
    }

