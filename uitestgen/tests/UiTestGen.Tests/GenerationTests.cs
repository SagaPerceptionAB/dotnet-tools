    [Test]
    public void Two_runs_give_identical_files()
    {
        var a = new PlaywrightGenerator().Generate(Catalog(), Options());
        var b = new PlaywrightGenerator().Generate(Catalog(), Options());
        Assert.That(b, Is.EqualTo(a));

        var dirA = NewTempDirectory();
        var dirB = NewTempDirectory();
        try
        {
            GeneratedFiles.Write(a, dirA);
            GeneratedFiles.Write(b, dirB);
            var left = Directory.GetFiles(dirA, "*", SearchOption.AllDirectories).Select(f => Path.GetRelativePath(dirA, f)).Order().ToList();
            var right = Directory.GetFiles(dirB, "*", SearchOption.AllDirectories).Select(f => Path.GetRelativePath(dirB, f)).Order().ToList();
            Assert.That(right, Is.EqualTo(left));
            foreach (var f in left) Assert.That(File.ReadAllText(Path.Combine(dirB, f)), Is.EqualTo(File.ReadAllText(Path.Combine(dirA, f))), f);
            // En tredje körning över en befintlig mapp ändrar ingenting.
            Assert.That(GeneratedFiles.Write(a, dirA), Is.EqualTo(0));
        }
        finally { Directory.Delete(dirA, true); Directory.Delete(dirB, true); }
    }

