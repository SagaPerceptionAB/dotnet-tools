    /// <summary>Argumenten till Fill-metoden med ett fält utbytt, så som testet ska skriva dem.</summary>
    private static string Fill(FormPlan plan, string field, string replacement)
    {
        var members = PageObjectWriter.Members(SignupView()).Single();
        return string.Join(", ", members.Parameters.Select(p =>
        {
            var f = plan.Form.Fields[p.Index];
            return $"{p.Name}: {(f.Name == field ? replacement : TestsWriter.ValueExpression(f, plan.Fields[p.Index].Valid!))}";
        }));
    }

