    [Test, Category("Slow")]
    public void Generated_project_builds()
    {
        // Mappen ligger under testets utdata, alltså i repot: det visar också att projektet inte ärver repots inställningar.
        var dir = NewTempDirectory(TestContext.CurrentContext.WorkDirectory);
        try
        {
            GeneratedFiles.Write(new PlaywrightGenerator().Generate(WithForms(Catalog()), Options(Backend.Mock)), dir);
            var psi = new ProcessStartInfo("dotnet", ["build", "--nologo", "-v", "q"])
            {
                WorkingDirectory = dir,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
            };
            psi.Environment["DOTNET_CLI_TELEMETRY_OPTOUT"] = "1";
            psi.Environment["DOTNET_NOLOGO"] = "1";
            using var process = Process.Start(psi)!;
            var output = process.StandardOutput.ReadToEndAsync();
            var error = process.StandardError.ReadToEndAsync();
            if (!process.WaitForExit(TimeSpan.FromMinutes(6)))
            {
                process.Kill(true);
                Assert.Fail("dotnet build tog för lång tid.");
            }
            Assert.That(process.ExitCode, Is.EqualTo(0), output.Result + error.Result);
        }
        finally { try { Directory.Delete(dir, true); } catch (IOException) { /* en kvarglömd byggprocess; mappen städas senare */ } }
    }

