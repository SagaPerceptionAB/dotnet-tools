    [Test]
    public void Invalid_values_break_their_own_rule()
    {
        var plan = Plan();
        Assert.That(plan.Cases, Is.Not.Empty);
        string Value(string field, RuleKind kind) => plan.Cases.Single(c => c.Field.Name == field && c.Rule.Kind == kind).Value.Text;
        foreach (var c in plan.Cases)
        {
            var other = plan.Fields.Single(f => f.Field.Name == "Password").Valid!.Text;
            var broken = FormPlan.Violations(c.Field, c.Value, other);
            Assert.That(broken, Does.Contain(c.Rule.Kind), $"{c.Field.Name} {c.Rule.Kind}");
            Assert.That(FormPlan.Typeable(c.Field, c.Value.Text), Is.True, $"{c.Field.Name} {c.Rule.Kind}");
        }
        Assert.Multiple(() =>
        {
            Assert.That(Value("Name", RuleKind.Required), Is.Empty);
            Assert.That(Value("Name", RuleKind.MinLength).Length, Is.EqualTo(2));
            Assert.That(Value("Name", RuleKind.MaxLength).Length, Is.EqualTo(21));
            Assert.That(Value("Age", RuleKind.Min), Is.EqualTo("17"));
            Assert.That(Value("Age", RuleKind.Max), Is.EqualTo("100"));
            Assert.That(Regex.IsMatch(Value("Sku", RuleKind.Pattern), "^[A-Z]{2}-[0-9]{4}$"), Is.False);
            Assert.That(Value("Email", RuleKind.Email), Is.EqualTo("inte-en-epost"));
            Assert.That(Value("Site", RuleKind.Url), Is.EqualTo("inte en adress"));
            Assert.That(Value("Confirm", RuleKind.Compare), Is.Not.EqualTo(plan.Fields.Single(f => f.Field.Name == "Password").Valid!.Text));
            Assert.That(Value("Name", RuleKind.MinLength), Is.Not.EqualTo(Value("Name", RuleKind.MaxLength)));
        });
        // Bara ett fält är fel i taget: övriga fält har sina giltiga värden i testet (se golden-testet ovan).
        Assert.That(plan.Cases.Count(c => c.Field.Name == "Name"), Is.EqualTo(3));
    }

