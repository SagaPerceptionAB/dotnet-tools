    [Test]
    public void The_plan_decides_who_checks_each_rule_and_the_tests_follow_it()
    {
        var form = new Form("Rules", null, Submit,
        [
            F("Named", FieldType.Text, [new(RuleKind.MaxLength, "5", "För långt."), new(RuleKind.MinLength, "2")]),
            F("Quiet", FieldType.Text, [new(RuleKind.MaxLength, "5"), new(RuleKind.Required)]),
            F("Pass", FieldType.Password),
            F("Again", FieldType.Password, [new(RuleKind.Compare, "Pass")]),
            F("Again2", FieldType.Password, [new(RuleKind.Compare, "Pass", "Olika.")]),
        ], null);
        var view = SignupView() with { Forms = [form] };
        var plan = FormPlan.Build(view, form, Options());

        string Describe(InvalidCase c) => $"{c.Field.Name}/{c.Rule.Kind}/{c.Checker}/{c.NeedsLongInput}";
        Assert.That(plan.Cases.Select(Describe), Is.EqualTo(new[]
        {
            "Named/MaxLength/App/True", "Named/MinLength/Browser/False", "Quiet/Required/Browser/False", "Again2/Compare/App/False",
        }), "MaxLength och Compare utan meddelande går inte att framkalla");
        Assert.That(plan.Cases.Select(c => c.Index), Is.EqualTo(new[] { 0, 0, 1, 4 }));

        var tests = new PlaywrightGenerator().Generate(new ViewCatalog([view], []), Options()).Single(f => f.Path == "Tests/SignupTests.g.cs").Content;
        Assert.That(Method(tests, "Rules_Named_MaxLength_shows_error"), Does.Contain("AllowTooLongAsync(view.Named)").And.Contain("ExpectMessageAsync(\"För långt.\")"));
        Assert.That(Method(tests, "Rules_Named_MinLength_shows_error"), Does.Not.Contain("AllowTooLong").And.Contain("ExpectInvalidAsync(view.Named)"));
        Assert.That(Method(tests, "Rules_Quiet_Required_shows_error"), Does.Contain("ExpectInvalidAsync(view.Quiet)"));
        Assert.That(Method(tests, "Rules_Again2_Compare_shows_error"), Does.Contain("ExpectMessageAsync(\"Olika.\")"));
        Assert.That(tests, Does.Not.Contain("Rules_Quiet_MaxLength").And.Not.Contain("Rules_Again_Compare"));
    }

